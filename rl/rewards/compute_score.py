"""Lightweight online reward for visual tool-use RL."""

from __future__ import annotations

import json
import re
from typing import Any, Optional

_TOOL_CALL_PATTERN = re.compile(r"<tool_call>(.*?)</tool_call>", re.DOTALL)
_WS_PATTERN = re.compile(r"\s+")


def _normalize_text(value: Any) -> str:
    if value is None:
        return ""
    text = str(value).strip()
    text = _WS_PATTERN.sub(" ", text)
    return text


def _canonical_mcq_letter(value: Any) -> Optional[str]:
    text = _normalize_text(value).upper()
    if not text:
        return None

    # Common answer forms: "A", "(A)", "Answer: A"
    match = re.search(r"\b([A-Z])\b", text)
    if match:
        return match.group(1)
    return None


def _extract_mcq_letter(solution_str: str) -> Optional[str]:
    text = _normalize_text(solution_str).upper()
    if not text:
        return None

    patterns = [
        r"(?:FINAL\s+ANSWER|ANSWER)\s*[:：]?\s*\(?\s*([A-Z])\s*\)?",
        r"\bOPTION\s*([A-Z])\b",
        r"\(([A-Z])\)",
    ]
    for pattern in patterns:
        match = re.search(pattern, text)
        if match:
            return match.group(1)

    # Last fallback: final standalone letter token.
    letters = re.findall(r"\b([A-Z])\b", text)
    if letters:
        return letters[-1]
    return None


def _extract_tool_call_stats(solution_str: str) -> tuple[int, int]:
    total = 0
    wellformed = 0
    for block in _TOOL_CALL_PATTERN.findall(solution_str or ""):
        total += 1
        try:
            payload = json.loads(block)
        except Exception:
            continue
        if not isinstance(payload, dict):
            continue
        if "name" not in payload or "arguments" not in payload:
            continue
        if not isinstance(payload["name"], str):
            continue
        if not isinstance(payload["arguments"], dict):
            continue
        wellformed += 1
    return total, wellformed


def _tool_exec_success_proxy(solution_str: str, tool_calls: int) -> float:
    if tool_calls == 0:
        return 0.0
    # This is intentionally text-only to keep online reward cheap; true execution
    # success should come from rollout-side tool metrics.
    lower = (solution_str or "").lower()
    error_markers = [
        "error when executing tool",
        "tool_execution_error",
        "invalid_tool_arguments_json",
        "tool failed",
    ]
    has_error = any(marker in lower for marker in error_markers)
    return 0.0 if has_error else 1.0


def compute_score(
    data_source: Optional[str],
    solution_str: str,
    ground_truth: str,
    extra_info: Optional[dict] = None,
    **kwargs,
) -> dict:
    """Compute online reward score.

    Returns a dict so verl logs extra per-sample diagnostics.
    """
    del data_source, kwargs
    extra_info = extra_info or {}

    gt_text = _normalize_text(ground_truth)
    solution_text = _normalize_text(solution_str)

    gt_letter = _canonical_mcq_letter(gt_text)
    pred_letter = _extract_mcq_letter(solution_text)

    if gt_letter is not None and pred_letter is not None:
        acc = 1.0 if pred_letter == gt_letter else 0.0
    else:
        acc = 1.0 if solution_text.lower() == gt_text.lower() and gt_text else 0.0

    tool_calls, wellformed = _extract_tool_call_stats(solution_str)
    has_tool_call = tool_calls > 0

    tool_bonus = 0.1 if has_tool_call else 0.0
    malformed_penalty = 0.05 if tool_calls > wellformed else 0.0

    score = acc + tool_bonus - malformed_penalty

    wellformed_rate = float(wellformed) / float(tool_calls) if tool_calls > 0 else 0.0
    tool_exec_success_proxy = _tool_exec_success_proxy(solution_str, tool_calls)

    # num_turns is generated by tool agent loop and passed via extra_info.
    num_turns = extra_info.get("num_turns")
    avg_tool_turns = float(tool_calls)
    if isinstance(num_turns, (int, float)) and num_turns > 0:
        avg_tool_turns = float(tool_calls) / float(num_turns)

    return {
        "score": float(score),
        "acc": float(acc),
        "tool_bonus": float(tool_bonus),
        "malformed_tool_penalty": float(malformed_penalty),
        "wellformed_tool_json_rate": float(wellformed_rate),
        "avg_tool_turns": float(avg_tool_turns),
        "tool_exec_success_proxy": float(tool_exec_success_proxy),
    }
